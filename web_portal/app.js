  async simulateIncomingCheckin() {
    const selectedEventId = this.state.selectedTelemetryEvent || 'all';

    // Strict Zero-Mock: Only verify real un-scanned tickets registered in Firestore
    let target = null;
    if (selectedEventId !== 'all') {
      target = this.state.students.find(s => s.eventId === selectedEventId && s.status !== 'checkedIn');
    }
    if (!target) {
      target = this.state.students.find(s => s.status !== 'checkedIn');
    }

    if (!target) {
      this.showToast('Không có vé thật nào đang chờ quét (Chưa Check-in). Vui lòng đăng ký 1 vé mới trên Mobile/Web App (:8081) để kiểm thử check-in!');
      return;
    }

    const ticketPayload = {
      ticketCode: target.ticketCode,
      eventId: target.eventId,
      studentName: target.name,
      gate: 'Trạm Test Lab (Cổng 1)'
    };

    try {
      this.showToast(`Đang xác thực vé thật ${target.ticketCode} qua Cloud Firestore...`);
      const res = await fetch('/api/tickets/checkin', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(ticketPayload)
      });
      const data = await res.json();

      if (res.ok && data.success) {
        this.state.lastScanTimeStr = `${this.formatVNDateTime(new Date().toISOString())} (Vừa quét xong)`;
        this.state.lastScanTicketCode = target.ticketCode;

        await this.loadAllRealData(false, true);
        this.renderTelemetryView();
        this.showToast(`[Check-in Thành Công] Vé thật ${target.ticketCode} - ${target.name} (${target.studentId}) đã check-in "${target.eventTitle}" (+5 ĐRL).`);
      } else {
        this.showToast(data.error || 'Lỗi khi điểm danh vé.');
      }
    } catch (e) {
      console.error('[simulateIncomingCheckin] Error:', e);
      this.showToast('Không thể kết nối đến máy chủ điểm danh.');
    }
  },


