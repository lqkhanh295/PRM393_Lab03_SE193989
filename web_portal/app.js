  // Get Event Temporal Status (Đã diễn ra, Đang diễn ra, Sắp diễn ra, Chưa diễn ra)
  getEventTemporalStatus(event) {
    if (!event || !event.date) {
      return {
        status: 'ended',
        label: 'Đã diễn ra',
        pillClass: 'pill-neutral',
        gateStatus: 'Đã đóng cổng',
        isPast: true,
        isOngoing: false,
        isUpcoming: false,
        isFuture: false,
        durationMs: 4 * 3600 * 1000,
        start: null,
        end: null
      };
    }

    let year, month, day;
    const trimmedDate = String(event.date).trim();
    if (trimmedDate.includes('/')) {
      const parts = trimmedDate.split('/');
      if (parts.length === 3) {
        const p0 = parseInt(parts[0], 10);
        const p1 = parseInt(parts[1], 10);
        const p2 = parseInt(parts[2], 10);
        if (p0 > 1000) {
          year = p0; month = p1 - 1; day = p2;
        } else {
          day = p0; month = p1 - 1; year = p2;
        }
      }
    } else if (trimmedDate.includes('-')) {
      const parts = trimmedDate.split('-');
      if (parts.length === 3) {
        const p0 = parseInt(parts[0], 10);
        const p1 = parseInt(parts[1], 10);
        const p2 = parseInt(parts[2], 10);
        if (p0 > 1000) {
          year = p0; month = p1 - 1; day = p2;
        } else {
          day = p0; month = p1 - 1; year = p2;
        }
      }
    }

    if (year === undefined) {
      const d = new Date(trimmedDate);
      if (!isNaN(d.getTime())) {
        year = d.getFullYear();
        month = d.getMonth();
        day = d.getDate();
      } else {
        return {
          status: 'ended',
          label: 'Đã diễn ra',
          pillClass: 'pill-neutral',
          gateStatus: 'Đã đóng cổng',
          isPast: true,
          isOngoing: false,
          isUpcoming: false,
          isFuture: false,
          durationMs: 4 * 3600 * 1000,
          start: null,
          end: null
        };
      }
    }

    let startHour = 8, startMin = 0;
    let endHour = 18, endMin = 0;

    if (event.time && typeof event.time === 'string') {
      const parts = event.time.split('-');
      if (parts.length >= 1) {
        const s = parts[0].trim().split(':');
        if (s.length >= 2) {
          startHour = parseInt(s[0], 10) || 0;
          startMin = parseInt(s[1], 10) || 0;
        }
      }
      if (parts.length >= 2) {
        const e = parts[1].trim().split(':');
        if (e.length >= 2) {
          endHour = parseInt(e[0], 10) || 0;
          endMin = parseInt(e[1], 10) || 0;
        }
      } else {
        endHour = Math.min(23, startHour + 4);
        endMin = startMin;
      }
    }

    const start = new Date(year, month, day, startHour, startMin, 0);
    const end = new Date(year, month, day, endHour, endMin, 0);
    const durationMs = Math.max(0, end.getTime() - start.getTime()) || (4 * 3600 * 1000);
    const now = new Date();
    const nowMs = now.getTime();
    const startMs = start.getTime();
    const endMs = end.getTime();

    // 1. ĐÃ DIỄN RA
    if (nowMs > endMs) {
      return {
        status: 'ended',
        label: 'Đã diễn ra',
        pillClass: 'pill-neutral',
        gateStatus: 'Đã đóng cổng',
        isPast: true,
        isOngoing: false,
        isUpcoming: false,
        isFuture: false,
        start,
        end,
        durationMs
      };
    }

    // 2. ĐANG DIỄN RA
    if (nowMs >= startMs && nowMs <= endMs) {
      return {
        status: 'ongoing',
        label: 'Đang diễn ra',
        pillClass: 'pill-positive',
        gateStatus: 'Đang mở cổng',
        isPast: false,
        isOngoing: true,
        isUpcoming: false,
        isFuture: false,
        start,
        end,
        durationMs
      };
    }

    // 3. SẮP DIỄN RA (Trong vòng 48 giờ tới hoặc cùng ngày trước giờ mở)
    const diffHours = (startMs - nowMs) / (3600 * 1000);
    if (diffHours > 0 && diffHours <= 48) {
      return {
        status: 'upcoming',
        label: 'Sắp diễn ra',
        pillClass: 'pill-warning',
        gateStatus: 'Sắp mở cổng',
        isPast: false,
        isOngoing: false,
        isUpcoming: true,
        isFuture: false,
        start,
        end,
        durationMs,
        diffHours
      };
    }

    // 4. CHƯA DIỄN RA (Còn hơn 48 giờ)
    return {
      status: 'future',
      label: 'Chưa diễn ra',
      pillClass: 'pill-neutral',
      gateStatus: 'Chưa mở cổng',
      isPast: false,
      isOngoing: false,
      isUpcoming: false,
      isFuture: true,
      start,
      end,
      durationMs
    };
  },

