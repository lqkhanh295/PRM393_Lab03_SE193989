  getDutySemanticStatus(assignment) {
    if (!assignment || assignment.status !== 'active') {
      return { key: 'revoked', label: 'Đã thu hồi', pillClass: 'pill-negative', isEffective: false, isEnded: false };
    }
    const evt = (this.state.liveEvents || []).find(e => e.id === assignment.eventId);
    if (evt) {
      const temp = this.getEventTemporalStatus(evt);
      if (temp.isPast) {
        return { key: 'ended', label: 'Đã kết thúc ca', pillClass: 'pill-neutral', isEffective: false, isEnded: true };
      }
      if (temp.isOngoing) {
        return { key: 'active', label: 'Đang trực cổng', pillClass: 'pill-positive', isEffective: true, isEnded: false };
      }
      return { key: 'active', label: 'Chờ mở cổng', pillClass: 'pill-accent', isEffective: true, isEnded: false };
    }
    return { key: 'active', label: 'Chờ mở cổng', pillClass: 'pill-accent', isEffective: true, isEnded: false };
  },

